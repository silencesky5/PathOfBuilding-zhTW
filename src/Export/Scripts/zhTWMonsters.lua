-- zhTW: monster names (spectres, minions) English -> Traditional Chinese
--
-- Pairs row N of Data/MonsterVarieties.datc64 with row N of the Traditional Chinese table.
-- Output: src/Data/zhTW/Monsters.lua { [english name] = zh }
--
-- Headless: set ZHTW_GGPK (see Export/zhTWRun.lua) and ZHTW_SCRIPT=Scripts/zhTWMonsters.lua

local t_insert = table.insert
local LANG = "Traditional Chinese"
local OUT_DIR = "../Data/zhTW/"
local NAME = "MonsterVarieties"

local ggpk = main.ggpk
if not ggpk or not ggpk.oozPath then
	print("zhTW: GGPK source is not set")
	return
end

-- UTF-8 -> UTF-16LE, for PowerShell -EncodedCommand (same as Scripts/zhTW.lua)
local function utf8to16le(s)
	local out = { }
	local i, n = 1, #s
	while i <= n do
		local c = s:byte(i)
		local cp
		if c < 0x80 then
			cp = c
			i = i + 1
		elseif c < 0xE0 then
			cp = (c % 0x20) * 0x40 + (s:byte(i + 1) % 0x40)
			i = i + 2
		elseif c < 0xF0 then
			cp = (c % 0x10) * 0x1000 + (s:byte(i + 1) % 0x40) * 0x40 + (s:byte(i + 2) % 0x40)
			i = i + 3
		else
			cp = (c % 0x08) * 0x40000 + (s:byte(i + 1) % 0x40) * 0x1000 + (s:byte(i + 2) % 0x40) * 0x40 + (s:byte(i + 3) % 0x40)
			i = i + 4
		end
		if cp >= 0x10000 then
			cp = cp - 0x10000
			local hi, lo = 0xD800 + math.floor(cp / 0x400), 0xDC00 + cp % 0x400
			t_insert(out, string.char(hi % 256, math.floor(hi / 256), lo % 256, math.floor(lo / 256)))
		else
			t_insert(out, string.char(cp % 256, math.floor(cp / 256)))
		end
	end
	return table.concat(out)
end

local function runUnicode(psCommand)
	local base64 = require("base64")
	return os.execute("powershell -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand " .. base64.encode(utf8to16le(psCommand)))
end

local function psQuote(s)
	return "'" .. s:gsub("'", "''") .. "'"
end

local function readFile(path)
	local f = io.open(ggpk.oozPath .. path:lower():gsub("/", "\\"), "rb")
	if not f then
		return nil
	end
	local data = f:read("*a")
	f:close()
	return data
end

local files = { "Data/" .. NAME .. ".datc64", "Data/" .. LANG .. "/" .. NAME .. ".datc64" }
if ggpk.path and ggpk.path ~= "" then
	local manifest = ggpk.oozPath .. "zhTW_extract_list.txt"
	local f = assert(io.open(manifest, "w"))
	for _, name in ipairs(files) do
		f:write(name:lower(), "\n")
	end
	f:close()
	runUnicode("Set-Location -LiteralPath " .. psQuote(ggpk.oozPath) ..
		"; Get-Content -LiteralPath " .. psQuote(manifest) ..
		" | & .\\bun_extract_file.exe extract-files " .. psQuote(ggpk.path) .. " .")
	os.remove(manifest)
end

local enRaw, tcRaw = readFile(files[1]), readFile(files[2])
if not enRaw or not tcRaw then
	print("zhTW: missing " .. NAME .. ".datc64 (English or " .. LANG .. ")")
	return
end
local en = new("Dat64File"):Dat64File(NAME, enRaw)
local tc = new("Dat64File"):Dat64File(NAME, tcRaw)
if en.rowCount ~= tc.rowCount then
	print(string.format("zhTW: WARNING row count mismatch (%d vs %d)", en.rowCount, tc.rowCount))
end

local function trim(s)
	return s and (s:gsub("^%s+", ""):gsub("%s+$", "")) or s
end
local function stripLinks(s)
	if type(s) ~= "string" or not s:find("[", 1, true) then
		return s
	end
	return (s:gsub("%[([^%[%]|]+)|([^%[%]]+)%]", "%2"):gsub("%[([^%[%]|]+)%]", "%1"))
end

local byId, byName, conflicts = { }, { }, { }
local count = 0
for i = 1, math.min(en.rowCount, tc.rowCount) do
	local enRow, tcRow = en:GetRowByIndex(i), tc:GetRowByIndex(i)
	local id = enRow.Id
	local enName, zhName = trim(stripLinks(enRow.Name)), trim(stripLinks(tcRow.Name))
	if id and id == tcRow.Id and enName and enName ~= "" and zhName and zhName ~= "" and zhName ~= enName
		and zhName:find("[\128-\255]") then
		byId[id] = zhName
		count = count + 1
		if byName[enName] == nil then
			byName[enName] = zhName
		elseif byName[enName] ~= zhName then
			conflicts[enName] = true
		end
	end
end
-- One English name with different Chinese names: keep the most common one
local votes = { }
for i = 1, math.min(en.rowCount, tc.rowCount) do
	local enRow = en:GetRowByIndex(i)
	local enName = trim(stripLinks(enRow.Name))
	local zh = byId[enRow.Id]
	if enName and conflicts[enName] and zh then
		votes[enName] = votes[enName] or { }
		votes[enName][zh] = (votes[enName][zh] or 0) + 1
	end
end
for enName, v in pairs(votes) do
	local best, bestN
	for zh, n in pairs(v) do
		if not bestN or n > bestN or (n == bestN and zh < best) then
			best, bestN = zh, n
		end
	end
	byName[enName] = best
end

local out = io.open(OUT_DIR .. "Monsters.lua", "w")
out:write("-- This file is automatically generated by Export/Scripts/zhTWMonsters.lua, do not edit!\n")
out:write("-- Monster data (c) Grinding Gear Games\n")
out:write("-- Source: ", tostring(ggpk.path or ggpk.oozPath), "\n")
out:write("-- Exported: ", os.date("%Y-%m-%d %H:%M"), "\n")
out:write("-- Monster names: English -> Traditional Chinese\n")
out:write("\nreturn ")
writeLuaTable(out, byName, 1)
out:write("\n")
out:close()
print(string.format("zhTW: %d monster varieties, %d names", count, (function() local n = 0 for _ in pairs(byName) do n = n + 1 end return n end)()))
