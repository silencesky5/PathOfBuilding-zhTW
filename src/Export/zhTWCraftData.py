"""zhTW: builds src/Data/zhTW/CraftData.lua for the 製作 tab from the crafting site's data.

The site (Poe-tool, craft-data.js) and POB share one source: RePoE, turned into craft-data.js by
the site's tools/build_craft_data.py. This script only reshapes that file into a Lua table with
the parts the POB tab uses (bases, mods, essences, stat translations), so both always agree.

usage: python src/Export/zhTWCraftData.py <path to craft-data.js>
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "Data" / "zhTW" / "CraftData.lua"

KEEP = ["version", "built", "source", "classes", "tags", "bases", "mods", "essences", "fossils", "resonators", "trans", "statTr", "curIcons"]
BASE_KEYS = ["id", "n", "c", "lv", "t", "imp", "nz", "is", "w", "h"]
MOD_KEYS = ["id", "n", "g", "gr", "ty", "lv", "sw", "gw", "at", "tg", "st", "tx", "nz", "d"]


def lua(v, indent=""):
	if v is None:
		return "nil"
	if v is True:
		return "true"
	if v is False:
		return "false"
	if isinstance(v, (int, float)):
		if isinstance(v, float) and v.is_integer():
			return str(int(v))
		return repr(v)
	if isinstance(v, str):
		return json.dumps(v, ensure_ascii=False)  # JSON escapes are valid Lua escapes except \u
	if isinstance(v, list):
		# nil holes would shorten the list in Lua: keep JSON null as false inside lists
		return "{" + ",".join("false" if x is None else lua(x) for x in v) + "}"
	if isinstance(v, dict):
		parts = []
		for k, x in v.items():
			if x is None:
				continue
			key = k if k.isidentifier() and k not in ("end", "and", "or", "not", "nil", "true", "false", "function", "local", "return", "if", "then", "else", "for", "in", "do", "while", "repeat", "until", "break") else "[" + json.dumps(k, ensure_ascii=False) + "]"
			parts.append(key + "=" + lua(x))
		return "{" + ",".join(parts) + "}"
	raise TypeError(type(v))


def fix_unicode_escapes(s):
	# json.dumps(ensure_ascii=False) leaves only control characters escaped as \uXXXX; Lua 5.1 has no \u
	import re
	return re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: "\\" + str(int(m.group(1), 16)) if int(m.group(1), 16) < 128 else m.group(0), s)


def main():
	src = pathlib.Path(sys.argv[1])
	text = src.read_text(encoding="utf-8")
	data = json.loads(text[text.index("{"):text.rstrip().rstrip(";").rindex("}") + 1])
	out = {k: data[k] for k in KEEP if k in data}
	out["bases"] = [{k: b[k] for k in BASE_KEYS if k in b} for b in data["bases"]]
	out["mods"] = [{k: m[k] for k in MOD_KEYS if k in m} for m in data["mods"]]
	body = fix_unicode_escapes(lua(out))
	assert "\\u" not in body, "unicode escape left"
	header = ("-- This file is automatically generated by Export/zhTWCraftData.py, do not edit!\n"
		"-- Source: the crafting site's craft-data.js (RePoE " + str(data.get("version")) + ", built " + str(data.get("built")) + ")\n")
	OUT.write_text(header + "return " + body + "\n", encoding="utf-8", newline="\n")
	print(f"{OUT}: {OUT.stat().st_size / 1024:.0f} KB, bases {len(out['bases'])}, mods {len(out['mods'])}, essences {len(out.get('essences', []))}")


main()
